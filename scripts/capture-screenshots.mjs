#!/usr/bin/env node
/**
 * Capture real screenshots of every portfolio project (desktop + mobile)
 * and register them in assets/js/screenshots.js.
 *
 *   npm i -D playwright && npx playwright install chromium
 *   node scripts/capture-screenshots.mjs            # all projects
 *   node scripts/capture-screenshots.mjs awaque wint  # only these ids
 *
 * Images are saved as optimized JPEGs in assets/img/projects/.
 * Once captured, the site uses them instead of live-generated screenshots.
 */
import { chromium } from "playwright";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import vm from "node:vm";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const outDir = path.join(root, "assets/img/projects");
const mapFile = path.join(root, "assets/js/screenshots.js");

const sandbox = { window: {} };
vm.runInNewContext(await readFile(path.join(root, "assets/js/projects.js"), "utf8"), sandbox);
const only = process.argv.slice(2);
const projects = sandbox.window.PORTFOLIO.projects.filter((p) => !p.hidden && (!only.length || only.includes(p.id)));

const existing = {};
if (existsSync(mapFile)) {
  const s = { window: {} };
  vm.runInNewContext(await readFile(mapFile, "utf8"), s);
  Object.assign(existing, s.window.SCREENSHOTS || {});
}

await mkdir(outDir, { recursive: true });
const browser = await chromium.launch();
const views = [
  { name: "desktop", viewport: { width: 1440, height: 950 }, deviceScaleFactor: 1 },
  { name: "mobile", viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true }
];

for (const p of projects) {
  const files = [];
  for (const v of views) {
    const ctx = await browser.newContext({ viewport: v.viewport, deviceScaleFactor: v.deviceScaleFactor, isMobile: !!v.isMobile });
    const page = await ctx.newPage();
    try {
      await page.goto(p.url, { waitUntil: "networkidle", timeout: 45000 });
      await page.waitForTimeout(1500); // let hero animations settle
      const rel = `assets/img/projects/${p.id}-${v.name}.jpg`;
      await page.screenshot({ path: path.join(root, rel), type: "jpeg", quality: 72 });
      files.push(rel);
      console.log("✓", p.id, v.name);
    } catch (err) {
      console.warn("✗", p.id, v.name, err.message.split("\n")[0]);
    } finally {
      await ctx.close();
    }
  }
  if (files.length) existing[p.id] = files;
}
await browser.close();

await writeFile(
  mapFile,
  "/* Generated by scripts/capture-screenshots.mjs — maps project id → local screenshots.\n" +
  "   While empty, the site shows live screenshots generated on the fly. */\n" +
  `window.SCREENSHOTS = ${JSON.stringify(existing, null, 2)};\n`
);
console.log(`\nSaved ${Object.keys(existing).length} project(s) to assets/js/screenshots.js`);
